"""
Conversion utility script to transform BuildNet3D scenes into ThermoScenes format.

This script converts BuildNet3D dataset scenes (containing RGB images, semantic
segmentation masks, and camera metadata) into the ThermoScenes format used for
thermal scene reconstruction and neural radiance field training. The conversion
includes train/eval split generation and dummy thermal data creation.
"""

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import tyro
from dataclasses_reverse_cli.reverse_cli import ReverseCli
from PIL import Image

from rebel_shape import logger


@dataclass
class BuildNetConversionParams(ReverseCli):
    buildnet_input_path: Path
    """
    Path to the BuildNet3D scene folder containing:
    - meta_data.json (camera parameters and frame information)
    - images/ (RGB .png files)
    - semantics/ (3-channel semantic segmentation .png files)
    - semantic_masks/ (binary mask .png files for object boundaries)
    """
    thermoscenes_output_path: Path
    """
    Path where the ThermoScenes-formatted dataset will be written.
    Creates images/ and thermal/ subdirectories with transforms.json
    """
    num_images: int | None = None
    """
    Number of images to keep from the original dataset (out of a total of 200 images).
    The default is keeping the entire dataset.
    """
    train_fraction: float = 0.9
    """
    Fraction of frames to assign to the training split (0.0 < train_fraction < 1.0).
    Remaining frames are assigned to the evaluation split.
    """

    def __post_init__(self) -> None:
        if not self.buildnet_input_path.exists():
            raise ValueError(
                f"BuildNet3D input scene {self.buildnet_input_path} does not exist."
            )
        if not self.thermoscenes_output_path.exists():
            raise ValueError(
                f"ThermoScenes output path {self.thermoscenes_output_path} "
                "does not exist."
            )

        if not (0.0 < self.train_fraction < 1.0):
            raise ValueError(
                "`train_fraction` must be a float between 0.0 and 1.0, exclusive."
            )


def convert_buildnet3d_to_thermoscenes(params: BuildNetConversionParams) -> None:
    """
    Convert a BuildNet3D scene folder into ThermoScenes format with train/eval split
    and a given number of images to keep out of the original 200 images.

    This function processes BuildNet3D scenes by:
    1. Loading camera intrinsics and frame metadata from meta_data.json
    2. Extracting the foreground of RGB images by selecting pixels with non-zero
       semantic segmentation masks
    3. Creating dummy thermal data from semantic segmentation maps
    4. Splitting frames into training and evaluation sets
    5. Generating ThermoScenes-compatible transforms.json with camera poses

    The conversion assumes BuildNet3D uses Blender's pinhole camera model with no
    distortion parameters. All frames must have identical camera intrinsics.

    Note that output images use 1-based indexing, e.g. frame_train_00001.png.
    Semantic segmentation maps are converted to grayscale thermal data based on their
    luminance values.
    Since the input images are generated by a Blender pinhole camera,
    the output camera model is always set to "OPEN_CV".

    :raises FileNotFoundError: If required input files or directories are missing
        (meta_data.json, images/, semantics/, semantic_masks/).
    :raises ValueError: If camera model is unsupported, no frames are found,
        or camera intrinsics differ between frames.


    """
    # --- 1) Validate input paths ---
    meta_path = params.buildnet_input_path / "meta_data.json"
    image_input_dir = params.buildnet_input_path / "images"
    semantics_input_dir = params.buildnet_input_path / "semantics"
    masks_input_dir = params.buildnet_input_path / "semantic_masks"

    if not meta_path.exists() or not meta_path.is_file():
        raise FileNotFoundError(f"meta_data.json not found at {meta_path}")
    if not image_input_dir.exists() or not image_input_dir.is_dir():
        raise FileNotFoundError(f"images/ folder not found at {image_input_dir}")
    if not semantics_input_dir.exists() or not semantics_input_dir.is_dir():
        raise FileNotFoundError(f"semantics/ folder not found at {semantics_input_dir}")
    if not masks_input_dir.exists() or not masks_input_dir.is_dir():
        raise FileNotFoundError(
            f"semantic_masks/ folder not found at {masks_input_dir}"
        )

    logger.info(
        f"Converting BuildNet3D scene at {params.buildnet_input_path} "
        f"to ThermoScenes format..."
    )

    # --- 2) Load and validate metadata ---
    with open(meta_path, "r") as f:
        meta = json.load(f)

    # Validate camera model
    cam_model = meta.get("camera_model", "").upper()
    if cam_model not in ("OPEN_CV", "PINHOLE"):
        raise ValueError(f"Unsupported camera_model '{cam_model}'")

    width: int = meta["width"]
    height: int = meta["height"]
    frames = meta.get("frames", [])
    if not frames:
        raise ValueError("No frames found in meta_data.json")

    logger.info(f"Found {len(frames)} frames with resolution {width}x{height}")

    # Fix the seed so that the same images are chosen every time
    np.random.seed(42)
    num_images = params.num_images if params.num_images is not None else len(frames)
    indices_to_keep = np.random.choice(len(frames), size=num_images, replace=False)
    frames = [frames[i] for i in indices_to_keep]

    logger.info(f"Keeping {len(frames)} frames with indices: \n {indices_to_keep}")

    # --- 3) Extract and verify camera intrinsics ---
    reference_intrinsics = frames[0].get("intrinsics")
    if not reference_intrinsics:
        raise ValueError("No intrinsics found in first frame")

    fx, fy = reference_intrinsics[0][0], reference_intrinsics[1][1]
    cx, cy = reference_intrinsics[0][2], reference_intrinsics[1][2]

    # Verify all frames have identical intrinsics
    for idx, frame in enumerate(frames[1:], start=1):
        if frame.get("intrinsics") != reference_intrinsics:
            raise ValueError(f"Intrinsics differ at frame index {idx}")

    # No distortion (Blender pinhole camera)
    k1 = k2 = p1 = p2 = 0.0

    # --- 4) Prepare output directories ---
    imgs_out = params.thermoscenes_output_path / "images"
    thermal_out = params.thermoscenes_output_path / "thermal"

    imgs_out.mkdir(parents=True, exist_ok=True)
    thermal_out.mkdir(parents=True, exist_ok=True)

    # --- 5) Initialize transforms structure ---
    transforms = {
        "w": width,
        "h": height,
        "fl_x": fx,
        "fl_y": fy,
        "cx": cx,
        "cy": cy,
        "k1": k1,
        "k2": k2,
        "p1": p1,
        "p2": p2,
        "camera_model": "OPEN_CV",  # Always use OPEN_CV for output
        "frames": [],
    }

    # --- 6) Compute train/eval split counts ---
    total_frames = len(frames)
    train_count = int(total_frames * params.train_fraction)
    train_idx = 1
    eval_idx = 1

    logger.info(
        f"Splitting {total_frames} frames: {train_count} train, "
        f"{total_frames - train_count} eval"
    )

    # --- 7) Process each frame ---
    for i, frame in enumerate(frames):
        # Determine split and counter
        if i < train_count:
            split, idx = "train", train_idx
            train_idx += 1
        else:
            split, idx = "eval", eval_idx
            eval_idx += 1

        # Generate output filename with 1-based indexing
        filename = f"frame_{split}_{idx:05d}.png"

        rgb_src = image_input_dir / frame["rgb_path"]
        semantic_src = semantics_input_dir / frame["segmentation_path"]
        mask_src = masks_input_dir / frame["segmentation_path"]

        if not rgb_src.exists() or not rgb_src.is_file():
            raise FileNotFoundError(f"RGB image not found: {rgb_src}")
        if not semantic_src.exists() or not semantic_src.is_file():
            raise FileNotFoundError(f"Semantics not found: {semantic_src}")
        if not mask_src.exists() or not mask_src.is_file():
            raise FileNotFoundError(f"Semantic mask not found: {mask_src}")

        rgb_img = Image.open(rgb_src).convert("RGBA")
        mask = Image.open(mask_src).convert("L")

        # Create alpha channel: transparent where mask is 0, opaque elsewhere
        alpha = mask.point(lambda p: 0 if p == 0 else 255)
        rgb_img.putalpha(alpha)
        rgb_img.save(imgs_out / filename)

        # Convert semantic mask to single-channel grayscale & save as thermal
        img_mask = Image.open(semantic_src).convert("L")
        img_mask.save(thermal_out / filename)

        # Add frame to transforms
        transforms["frames"].append(
            {
                "file_path": f"images/{filename}",
                "transform_matrix": frame["camtoworld"],
                "thermal_file_path": f"thermal/{filename}",
            }
        )

    # --- 8) Write transforms.json ---
    transforms_path = params.thermoscenes_output_path / "transforms.json"
    with open(transforms_path, "w") as f:
        json.dump(transforms, f, indent=4)

    logger.info(f"Conversion complete. transforms.json written to {transforms_path}")


if __name__ == "__main__":
    parameters = tyro.cli(BuildNetConversionParams)

    convert_buildnet3d_to_thermoscenes(params=parameters)
